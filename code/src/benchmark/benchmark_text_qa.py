#!/usr/bin/env python3
"""
Text-based factual multiple-choice QA benchmark evaluation.

Evaluates multiple LLMs on MC questions generated by the factual QA
generator pipeline.

Pipeline:
  1. Cold evaluation — question only (no system prompt, no context)
  2. MC scoring — deterministic set equality after Gemini-Flash letter
     extraction
  3. Excel export — per-model responses, extracted letters, and accuracy

Usage:
    export OPENROUTER_API_KEY="sk-or-..."
    python scripts/run_benchmark.py --input output/qa_pairs.xlsx
"""

from __future__ import annotations

import json
import logging
import os
import re
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any

import httpx
import pandas as pd
from openpyxl.styles import Alignment, Font

from src.benchmark.answer_extractor import GeminiAnswerExtractor
from src.llm.openrouter_client import OpenRouterClient

logger = logging.getLogger(__name__)

# ── Default configuration ─────────────────────────────────────────────────────

DEFAULT_EVAL_MODELS: dict[str, str] = {
    "gpt-5.4":            "openai/gpt-5.4",
    "gpt-5.4-mini":       "openai/gpt-5.4-mini",
    "gpt-5.2-chat":       "openai/gpt-5.2-chat",
    "claude-sonnet-4.6":  "anthropic/claude-sonnet-4.6",
    "claude-haiku-4.5":   "anthropic/claude-haiku-4.5",
    "gemini-3.1-pro":     "google/gemini-3.1-pro-preview",
    "gemini-3-flash":     "google/gemini-3-flash-preview",
    "deepseek-v3.2":      "deepseek/deepseek-v3.2:exacto",
    "mistral-large-3":    "mistralai/mistral-large-2512",
    "qwen-3.6-plus":      "qwen/qwen3.6-plus",
}

# Bumped when the cold-eval prompt construction changes. Cache keys include
# this so prompt edits auto-invalidate prior responses.
PROMPT_VERSION = "v2"

# ── Client-side Exa search orchestration ─────────────────────────────────────
# Every model gets an `exa_search(query)` function tool. The model decides
# when to search and what to query; this code receives the tool_call,
# calls Exa directly (no OpenRouter web_search plugin), and feeds results
# back. Hard caps prevent runaway loops.
MAX_SEARCH_ROUNDS = 3
MAX_TOTAL_URLS = 10
EXA_RESULTS_PER_QUERY = 5
EXA_SNIPPET_CHARS = 1200
EXA_TIMEOUT_S = 20.0
EXA_SEARCH_URL = "https://api.exa.ai/search"

# Cache key suffix embedding the orchestrator params that influence response
# text. A change to MAX_SEARCH_ROUNDS / MAX_TOTAL_URLS / EXA_SNIPPET_CHARS
# auto-invalidates cached responses.
EXA_VERSION = f"exa_r{MAX_SEARCH_ROUNDS}_u{MAX_TOTAL_URLS}_s{EXA_SNIPPET_CHARS}"

# Function-tool schema sent to every model via OpenRouter's tools=[].
EXA_SEARCH_TOOL: dict = {
    "type": "function",
    "function": {
        "name": "exa_search",
        "description": (
            "Search the web for authoritative pages relevant to the "
            "question. Returns a numbered list of URLs each followed by "
            "a short text snippet."
        ),
        "parameters": {
            "type": "object",
            "properties": {
                "query": {
                    "type": "string",
                    "description": "The search query to send to Exa.",
                },
            },
            "required": ["query"],
            "additionalProperties": False,
        },
    },
}

# Regex used to pull cited URLs out of the model's final text response
# (replaces the OpenRouter annotations array we used to read).
_URL_RE = re.compile(r"https?://[^\s\)\]\,\>\"']+", re.IGNORECASE)

# ── Simple retry on empty extraction ─────────────────────────────────────────
# After the first cold-eval call, run the answer extractor on the response.
# If the extractor returns no committed letters (empty answer), retry the
# SAME call with the SAME prompt, model, params, tools. One retry only;
# if still empty, accept the response (will score as wrong in stage 2).
SIMPLE_RETRY_ON_EMPTY = True


def _intervention_suffix(
    model_name: str,
    enabled: bool = True,
) -> str:
    """Cache-key suffix encoding the Exa orchestrator's tunables.

    Every model gets the orchestrator's ``EXA_VERSION`` tag (since the
    Exa loop runs for everyone). With ``enabled=False`` (the
    ``--baseline`` kill switch) the suffix collapses to empty so baseline
    runs reuse a separate cache.
    """
    if not enabled:
        return ""
    return f"|{EXA_VERSION}"


def _extract_cited_urls(text: str) -> list[str]:
    """Pull http(s):// URLs out of the model's final response text.

    Deduped, ordered by first appearance, trailing punctuation stripped.
    """
    if not text:
        return []
    seen: set[str] = set()
    out: list[str] = []
    for m in _URL_RE.finditer(text):
        url = m.group(0).rstrip(".,;:!?")
        if url and url not in seen:
            seen.add(url)
            out.append(url)
    return out


def _normalize_city(value: str) -> str:
    """Convert ``new_south_wales`` -> ``New South Wales``; empty string passes through.

    Used at the state/provincial tier of the 3-country COFOG benchmark to
    turn snake_case state short-names from the QA Excel into a
    human-readable form for the prompt context line.
    """
    if not value:
        return ""
    return " ".join(part.capitalize() for part in str(value).replace("-", "_").split("_") if part)

def model_extras(
    model_id: str,
    task_tag: str = "MC",
    model_name: str = "",
) -> tuple[dict[str, Any] | None, int]:
    """Return ``(extra_body, max_tokens)`` for a model.

    All per-provider reasoning overrides have been stripped — every model
    gets ``extra_body=None`` and ``max_tokens=8192``. Signature retained
    for diagnostic-script compatibility.
    """
    return None, 8192


# ── Configuration dataclass ───────────────────────────────────────────────────

@dataclass
class BenchmarkConfig:
    """All tuneable knobs for a benchmark run."""

    input_path:      Path              = field(default_factory=lambda: Path("output/qa_pairs.xlsx"))
    output_path:     Path              = field(default_factory=lambda: Path("output/benchmark_results.xlsx"))
    cache_path:      Path              = field(default_factory=lambda: Path("output/benchmark_cache.json"))
    eval_models:     dict[str, str]    = field(default_factory=lambda: dict(DEFAULT_EVAL_MODELS))
    max_workers:     int               = 5
    request_timeout: float             = 180.0
    max_retries:     int               = 3
    retry_delay:     float             = 5.0
    limit_rows:      int | None        = None
    institution_name: str              = ""
    # Country appended to the per-row state/province name when
    # ``institution_name`` is not set. Used at the state layer to
    # disambiguate names like "Victoria" or "Quebec" by adding country
    # context: "This question is about Victoria, Australia." Empty string
    # is a no-op.
    country_suffix:  str               = ""
    # Per-row institution column. When set, the value of df[institution_column]
    # for each row is used directly as the prompt context — e.g. the
    # ``institution`` field in municipal QA inputs holds "City of Brisbane",
    # "City of Toronto", "City of New York", which become
    # "This question is about City of Brisbane." Takes precedence over
    # country_suffix; ignored when ``institution_name`` is set (the uniform
    # federal-tier override wins).
    institution_column: str            = ""
    user_location:   str               = ""
    # Master kill switch for per-model interventions (V3 prompt, effort:low,
    # empty-retry). When False, _intervention_suffix returns "" for all
    # models so cache keys collapse to baseline form, and the retry pass
    # is skipped. Set via the ``--baseline`` CLI flag.
    interventions_enabled: bool         = True


# ── Benchmark class ───────────────────────────────────────────────────────────

class TextQABenchmark:
    """Evaluates multiple LLMs on factual QA pairs (text only)."""

    def __init__(self, config: BenchmarkConfig | None = None) -> None:
        self.config = config or BenchmarkConfig()
        self.api_key = os.environ.get("OPENROUTER_API_KEY", "")
        if not self.api_key:
            raise ValueError(
                "OPENROUTER_API_KEY not set.  "
                "Export it before running: export OPENROUTER_API_KEY='sk-or-...'"
            )
        self.exa_api_key = os.environ.get("EXA_API_KEY", "")
        if not self.exa_api_key:
            raise ValueError(
                "EXA_API_KEY not set. The client-side Exa orchestrator "
                "calls Exa directly for every model. "
                "Export it before running: export EXA_API_KEY='...'"
            )
        self._client = OpenRouterClient(
            api_key=self.api_key,
            timeout=self.config.request_timeout,
            max_retries=self.config.max_retries,
            base_delay=self.config.retry_delay,
        )
        self._exa_http = httpx.Client(timeout=EXA_TIMEOUT_S)
        self.cache: dict[str, str] = self._load_cache()
        self._extractor = GeminiAnswerExtractor()

    # ── Cache ─────────────────────────────────────────────────────────────────

    def _load_cache(self) -> dict[str, str]:
        if self.config.cache_path.exists():
            with open(self.config.cache_path, "r", encoding="utf-8") as f:
                return json.load(f)
        return {}

    def _save_cache(self) -> None:
        self.config.cache_path.parent.mkdir(parents=True, exist_ok=True)
        with open(self.config.cache_path, "w", encoding="utf-8") as f:
            json.dump(self.cache, f, ensure_ascii=False, indent=2)

    # ── Exa search (client-side, no OpenRouter web_search plugin) ─────────────

    def _exa_search(self, query: str) -> list[tuple[str, str]]:
        """Single Exa /search call. Returns list of (url, snippet) tuples.

        Snippets are clipped to ``EXA_SNIPPET_CHARS``. Errors return an
        empty list (caller decides what to send back to the model).
        """
        if not query.strip():
            return []
        try:
            r = self._exa_http.post(
                EXA_SEARCH_URL,
                headers={
                    "x-api-key": self.exa_api_key,
                    "Content-Type": "application/json",
                },
                json={
                    "query": query,
                    "num_results": EXA_RESULTS_PER_QUERY,
                    "contents": {"text": True},
                },
            )
            r.raise_for_status()
            results = (r.json() or {}).get("results", []) or []
        except Exception as exc:  # noqa: BLE001
            logger.warning("Exa /search failed for %r: %s", query[:80], exc)
            return []
        out: list[tuple[str, str]] = []
        for item in results:
            url = (item.get("url") or "").strip()
            text = (item.get("text") or "").strip()
            if url:
                out.append((url, text[:EXA_SNIPPET_CHARS]))
        return out

    @staticmethod
    def _format_tool_result(
        kept: list[tuple[str, str]],
        round_idx: int,
        url_index_base: int,
    ) -> str:
        if not kept:
            return "[no results]"
        lines = [f"Round {round_idx} results:"]
        for i, (url, snippet) in enumerate(kept, url_index_base + 1):
            lines.append(f"[{i}] {url}\n{snippet}")
        return "\n\n".join(lines)

    # ── Cold evaluation (agentic Exa loop, no OpenRouter web_search plugin) ──

    def _call_model_raw(
        self,
        model_id: str,
        question: str,
        city: str = "",
        model_name: str = "",
        qid: str | int = "",
        institution_value: str = "",
    ) -> dict[str, Any]:
        """Run the agentic Exa tool-calling loop for one (model, question) pair.

        Flow:
          1. Compose the user prompt (institution context + question +
             "Select all that apply").
          2. Call OpenRouter with the ``exa_search`` function tool exposed.
          3. If the model returns ``tool_calls``, call Exa client-side
             for each query, send results back, loop.
          4. Cap: ``MAX_SEARCH_ROUNDS`` rounds and ``MAX_TOTAL_URLS``
             unique URLs across all rounds.
          5. Final assistant text → ``cited_urls`` via regex.

        Returns a dict with keys:
            text, searched, cited_urls (list), retrieved_urls (list),
            search_count (rounds used), finish_reason, prompt_tokens,
            completion_tokens, reasoning_tokens.
        """
        # Build the per-row context name. Priority:
        #   1. ``--institution`` (uniform across all rows; used for federal)
        #   2. ``institution_value`` (per-row value from --institution-column;
        #      used at the municipal tier, where the row's ``institution``
        #      field is e.g. "City of Brisbane", "City of Toronto"). Used
        #      as-is, no normalization.
        #   3. normalized city + optional ``--country-suffix`` for state layer:
        #      "Victoria" + ", Australia" -> "Victoria, Australia"
        #   4. normalized city alone (no country suffix configured)
        if self.config.institution_name:
            context_name = self.config.institution_name
        elif (institution_value or "").strip():
            context_name = institution_value.strip()
        else:
            base = _normalize_city(city)
            suffix = (self.config.country_suffix or "").strip()
            if base and suffix:
                context_name = f"{base}, {suffix}"
            else:
                context_name = base

        parts: list[str] = []
        if context_name:
            parts.append(f"This question is about {context_name}.")
        parts.append(question)
        body = "\n\n".join(parts)
        prompt = f"{body}\n\n(Select all that apply)"

        extra_body, max_tokens = model_extras(model_id, "MC", model_name)

        response = self._agentic_search(
            model_id=model_id,
            user_prompt=prompt,
            model_name=model_name,
            extra_body=extra_body,
            max_tokens=max_tokens,
            stage="cold_eval",
        )

        # Simple retry: if the answer extractor returns no committed letters,
        # re-run the SAME agentic loop once with the SAME prompt and params.
        if SIMPLE_RETRY_ON_EMPTY:
            extracted_first = self._extractor.extract(
                response_text=response.get("text", "") or "",
                valid_labels=["A", "B", "C", "D", "E", "F", "G", "H"],
                qid=str(qid) if qid != "" else "_anon",
                model_name=model_name,
                cache_key_extra="|retry_check_v1",
            )
            if not extracted_first:
                logger.info(
                    "Simple-retry: %s qid=%s extracted empty, re-running once",
                    model_name, qid,
                )
                first_call_tokens = {
                    "finish_reason":     response.get("finish_reason"),
                    "prompt_tokens":     response.get("prompt_tokens"),
                    "completion_tokens": response.get("completion_tokens"),
                    "reasoning_tokens":  response.get("reasoning_tokens"),
                }
                response = self._agentic_search(
                    model_id=model_id,
                    user_prompt=prompt,
                    model_name=model_name,
                    extra_body=extra_body,
                    max_tokens=max_tokens,
                    stage="cold_eval_simple_retry",
                )
                response["retry_used"] = True
                response["retry_first_call_tokens"] = first_call_tokens

        return response

    def _agentic_search(
        self,
        model_id: str,
        user_prompt: str,
        model_name: str,
        extra_body: dict[str, Any] | None,
        max_tokens: int,
        stage: str,
    ) -> dict[str, Any]:
        """Drive the multi-turn ``exa_search`` tool-call loop for one question.

        Each iteration:
          * Send the running message list to OpenRouter with the Exa tool.
          * If the model emits ``tool_calls``, run Exa client-side for
            each, append a ``tool`` message with the formatted snippets.
          * Otherwise (final text) break out.

        Hard caps: ``MAX_SEARCH_ROUNDS`` iterations, ``MAX_TOTAL_URLS``
        unique URLs accumulated across all rounds. Once the URL cap is
        hit, further ``exa_search`` calls return ``[budget exhausted]``.
        """
        messages: list[dict[str, Any]] = [
            {"role": "user", "content": user_prompt},
        ]
        retrieved_urls: list[str] = []
        seen_urls: set[str] = set()
        rounds_used = 0
        total_prompt_tokens = 0
        total_completion_tokens = 0
        total_reasoning_tokens = 0
        finish_reason: str | None = None
        final_text = ""

        for round_idx in range(MAX_SEARCH_ROUNDS + 1):
            result = self._client.chat_with_tools(
                model=model_id,
                messages=messages,
                tools=[EXA_SEARCH_TOOL],
                temperature=0,
                max_tokens=max_tokens,
                stage=stage,
                extra_body=extra_body,
            )
            message = result.get("message", {}) or {}
            finish_reason = result.get("finish_reason")
            usage = result.get("usage", {}) or {}
            total_prompt_tokens += int(usage.get("prompt_tokens") or 0)
            total_completion_tokens += int(usage.get("completion_tokens") or 0)
            comp_details = usage.get("completion_tokens_details") or {}
            total_reasoning_tokens += int(comp_details.get("reasoning_tokens") or 0)

            tool_calls = message.get("tool_calls") or []
            content = (message.get("content") or "").strip()

            if not tool_calls:
                # Model committed to a text answer; we're done.
                final_text = content
                break

            # Hit the rounds cap — even if the model wants to search more,
            # stop. Treat the assistant content (if any) as the final answer.
            if round_idx >= MAX_SEARCH_ROUNDS:
                final_text = content
                logger.info(
                    "[%s qid=%s] Reached MAX_SEARCH_ROUNDS=%d, stopping.",
                    model_name, "?", MAX_SEARCH_ROUNDS,
                )
                break

            # Append the assistant message verbatim (preserves tool_calls).
            messages.append(message)

            # Process every tool call this turn — each becomes one Exa /search.
            for tc in tool_calls:
                fn = (tc.get("function") or {})
                if fn.get("name") != "exa_search":
                    messages.append({
                        "role": "tool",
                        "tool_call_id": tc.get("id", ""),
                        "content": f"[unknown tool: {fn.get('name')!r}]",
                    })
                    continue

                try:
                    args = json.loads(fn.get("arguments") or "{}")
                except json.JSONDecodeError:
                    args = {}
                query = (args.get("query") or "").strip()

                if len(retrieved_urls) >= MAX_TOTAL_URLS:
                    tool_payload = (
                        f"[budget exhausted: {MAX_TOTAL_URLS} URLs already "
                        "retrieved. Answer with the information you have.]"
                    )
                elif not query:
                    tool_payload = "[error: empty query]"
                else:
                    raw = self._exa_search(query)
                    remaining = MAX_TOTAL_URLS - len(retrieved_urls)
                    kept: list[tuple[str, str]] = []
                    for url, snippet in raw:
                        if url in seen_urls:
                            continue
                        if remaining <= 0:
                            break
                        seen_urls.add(url)
                        retrieved_urls.append(url)
                        kept.append((url, snippet))
                        remaining -= 1
                    tool_payload = self._format_tool_result(
                        kept, round_idx + 1, len(retrieved_urls) - len(kept),
                    )

                messages.append({
                    "role": "tool",
                    "tool_call_id": tc.get("id", ""),
                    "content": tool_payload,
                })

            rounds_used = round_idx + 1

        cited_urls = _extract_cited_urls(final_text)
        return {
            "text":              final_text,
            "searched":          rounds_used > 0,
            "cited_urls":        cited_urls,
            "retrieved_urls":    retrieved_urls,
            "search_count":      rounds_used,
            "finish_reason":     finish_reason,
            "prompt_tokens":     total_prompt_tokens or None,
            "completion_tokens": total_completion_tokens or None,
            "reasoning_tokens":  total_reasoning_tokens or None,
        }

    def run_cold_eval(
        self, df: pd.DataFrame,
    ) -> tuple[
        dict[str, dict[int, str]],
        dict[str, dict[int, str]],
        dict[str, dict[int, bool]],
        dict[str, dict[int, str]],
        dict[str, dict[int, str]],
    ]:
        """Run cold evaluation for every question × model.

        Returns ``(responses, timestamps, searched, cited_urls, retrieved_urls)``
        where each is ``{model_name: {row_idx: value}}``.  Timestamps are
        ISO-format strings captured at the moment a model returns its
        answer (empty string for cache hits). ``cited_urls`` and
        ``retrieved_urls`` are pipe-joined strings (``" | "``).
        """
        all_responses: dict[str, dict[int, str]] = {}
        all_timestamps: dict[str, dict[int, str]] = {}
        all_searched: dict[str, dict[int, bool]] = {}
        all_cited_urls: dict[str, dict[int, str]] = {}
        all_retrieved_urls: dict[str, dict[int, str]] = {}

        for model_name, model_id in self.config.eval_models.items():
            logger.info("── Cold eval: %s (%s) ──", model_name, model_id)
            model_responses: dict[int, str] = {}
            model_timestamps: dict[int, str] = {}
            model_searched: dict[int, bool] = {}
            model_cited_urls: dict[int, str] = {}
            model_retrieved_urls: dict[int, str] = {}
            tasks: list[tuple[int, str, str, str, str, str]] = []
            interv_suffix = _intervention_suffix(
                model_name, self.config.interventions_enabled,
            )
            # Per-row institution column lookup: when configured, each task
            # carries the row's value from this column to be used as prompt
            # context. Empty string when the column is not configured.
            inst_col = (self.config.institution_column or "").strip()

            for idx, row in df.iterrows():
                cache_key = f"{model_name}|{idx}|{PROMPT_VERSION}{interv_suffix}"
                if cache_key in self.cache:
                    cached = self.cache[cache_key]
                    if isinstance(cached, dict):
                        model_responses[idx] = cached.get("text", "")
                        model_searched[idx] = cached.get("searched", False)
                        model_cited_urls[idx] = cached.get("cited_urls_str", "")
                        model_retrieved_urls[idx] = cached.get(
                            "retrieved_urls_str", "",
                        )
                    else:
                        # Legacy string cache — no search metadata available
                        model_responses[idx] = cached
                        model_searched[idx] = False
                        model_cited_urls[idx] = ""
                        model_retrieved_urls[idx] = ""
                    model_timestamps[idx] = ""
                else:
                    inst_value = (
                        str(row.get(inst_col, "") or "") if inst_col else ""
                    )
                    tasks.append((
                        idx, row["question_text"], cache_key,
                        row.get("city", ""), inst_value,
                    ))

            logger.info("  %d cached, %d to fetch", len(model_responses), len(tasks))

            if tasks:
                def _fetch(args: tuple[int, str, str, str, str]) -> tuple[int, dict, str, str]:
                    idx, question, cache_key, city, inst_value = args
                    result = self._call_model_raw(
                        model_id, question, city=city, model_name=model_name,
                        qid=idx, institution_value=inst_value,
                    )
                    ts = datetime.now().isoformat()
                    return idx, result, cache_key, ts

                workers_for_model = self.config.max_workers
                logger.info("  workers=%d for %s", workers_for_model, model_name)

                with ThreadPoolExecutor(max_workers=workers_for_model) as pool:
                    futures = {pool.submit(_fetch, t): t for t in tasks}
                    done = 0
                    for future in as_completed(futures):
                        idx, result, cache_key, ts = future.result()
                        text = result["text"]
                        searched = result["searched"]
                        cited_urls_str = " | ".join(result.get("cited_urls") or [])
                        retrieved_urls_str = " | ".join(
                            result.get("retrieved_urls") or []
                        )

                        model_responses[idx] = text
                        model_timestamps[idx] = ts
                        model_searched[idx] = searched
                        model_cited_urls[idx] = cited_urls_str
                        model_retrieved_urls[idx] = retrieved_urls_str

                        cache_entry = {
                            "text":               text,
                            "searched":           searched,
                            "cited_urls_str":     cited_urls_str,
                            "retrieved_urls_str": retrieved_urls_str,
                            "search_count":       result.get("search_count"),
                            "finish_reason":      result.get("finish_reason"),
                            "prompt_tokens":      result.get("prompt_tokens"),
                            "completion_tokens":  result.get("completion_tokens"),
                            "reasoning_tokens":   result.get("reasoning_tokens"),
                        }
                        # Empty-retry telemetry — only present when retry
                        # was attempted. Cache-only fields; the Excel
                        # exporter does not read them.
                        if result.get("retry_used"):
                            cache_entry["retry_used"] = True
                            cache_entry["retry_first_call_tokens"] = (
                                result.get("retry_first_call_tokens")
                            )
                        self.cache[cache_key] = cache_entry
                        done += 1
                        if done % 20 == 0 or done == len(tasks):
                            logger.info("  %d / %d responses", done, len(tasks))
                            self._save_cache()

                self._save_cache()

            all_responses[model_name] = model_responses
            all_timestamps[model_name] = model_timestamps
            all_searched[model_name] = model_searched
            all_cited_urls[model_name] = model_cited_urls
            all_retrieved_urls[model_name] = model_retrieved_urls
            logger.info("  %d total responses for %s", len(model_responses), model_name)

        return (
            all_responses, all_timestamps, all_searched,
            all_cited_urls, all_retrieved_urls,
        )

    # ── MC scoring (deterministic) ────────────────────────────────────────────

    @staticmethod
    def _extract_valid_labels(question_text: str) -> set[str]:
        """Extract valid option labels (A, B, C…) from MC question text."""
        return set(re.findall(r"^\s*([A-Z])\.", question_text, re.MULTILINE))

    def score_mc(
        self, df: pd.DataFrame, responses: dict[str, dict[int, str]],
    ) -> dict[str, dict[int, dict]]:
        """MC scoring via Gemini Flash extractor + strict set equality."""
        results: dict[str, dict[int, dict]] = {
            m: {} for m in self.config.eval_models
        }

        # Build extraction tasks — (model_name, idx, response, valid_labels, qid, gold_set)
        tasks: list[tuple[str, int, str, list[str], str, set[str]]] = []
        for model_name in self.config.eval_models:
            for idx in df.index:
                question  = df.at[idx, "question_text"]
                gold_text = str(df.at[idx, "gold_answer"])
                resp_text = responses[model_name].get(idx, "") or ""
                valid_set = self._extract_valid_labels(question)
                valid_lst = sorted(valid_set)
                gold_set  = set(re.findall(r"[A-Z]", gold_text.upper())) & valid_set
                qid_val   = (
                    df.at[idx, "question_id"]
                    if "question_id" in df.columns else f"row_{idx}"
                )
                tasks.append(
                    (model_name, int(idx), resp_text, valid_lst, str(qid_val), gold_set),
                )

        def _extract_one(args: tuple) -> tuple[str, int, dict]:
            model_name, idx, resp_text, valid_lst, qid_str, gold_set = args
            extracted_letters = self._extractor.extract(
                resp_text, valid_lst, qid_str, model_name,
                cache_key_extra=_intervention_suffix(
                    model_name, self.config.interventions_enabled,
                ),
            )
            extracted_set = set(extracted_letters)
            return model_name, idx, {
                "correct":   extracted_set == gold_set,
                "extracted": extracted_set,
                "gold":      gold_set,
            }

        workers = max(1, getattr(self.config, "max_workers", 1) or 1)
        total = len(tasks)
        if workers <= 1 or not tasks:
            for t in tasks:
                mn, ix, r = _extract_one(t)
                results[mn][ix] = r
        else:
            with ThreadPoolExecutor(max_workers=workers) as pool:
                futures = {pool.submit(_extract_one, t): t for t in tasks}
                done = 0
                for future in as_completed(futures):
                    mn, ix, r = future.result()
                    results[mn][ix] = r
                    done += 1
                    if done % 50 == 0 or done == total:
                        logger.info("  Extractor: %d / %d", done, total)

        # Persist extractor cache after the batch
        self._extractor.flush_cache()

        return results

    # ── Excel export ──────────────────────────────────────────────────────────

    def export_results(
        self,
        df: pd.DataFrame,
        responses: dict[str, dict[int, str]],
        mc_scores: dict[str, dict[int, dict]],
        timestamps: dict[str, dict[int, str]] | None = None,
        searched: dict[str, dict[int, bool]] | None = None,
        cited_urls: dict[str, dict[int, str]] | None = None,
        retrieved_urls: dict[str, dict[int, str]] | None = None,
    ) -> Path:
        """Write MC benchmark results to a two-sheet Excel workbook.

        Sheets: Summary, Results.

        Results column order:
            question metadata: question_id, question_text, gold_answer,
                valid_labels, category, city, source_url, page_title,
                supporting_quotes
            per-model groups (one column per model, all models adjacent
                within each group): response_, searched_, retrieved_urls_,
                cited_urls_, extracted_, correct_
            final: pct_of_models_correct

        Summary columns: model, total_count, accuracy.
        """
        model_names = list(self.config.eval_models.keys())

        # ── Build per-question result rows ────────────────────────────────────
        rows: list[dict] = []
        for idx, row in df.iterrows():
            valid_labels = sorted(self._extract_valid_labels(str(row["question_text"])))
            r: dict = {
                "question_id":       row.get("question_id", ""),
                "question_text":     row["question_text"],
                "gold_answer":       row.get("gold_answer", ""),
                "valid_labels":      ",".join(valid_labels),
                "category":          row.get("category", ""),
                "city":              row.get("city", ""),
                "source_url":        row.get("source_url", ""),
                "page_title":        row.get("page_title", ""),
                "supporting_quotes": row.get("supporting_quotes", ""),
            }

            correct_count = 0
            for m in model_names:
                r[f"response_{m}"]   = responses[m].get(idx, "")
                r[f"searched_{m}"]   = (
                    searched.get(m, {}).get(idx, False) if searched else False
                )
                r[f"retrieved_urls_{m}"] = (
                    retrieved_urls.get(m, {}).get(idx, "") if retrieved_urls else ""
                )
                r[f"cited_urls_{m}"] = (
                    cited_urls.get(m, {}).get(idx, "") if cited_urls else ""
                )

                mc = mc_scores.get(m, {}).get(idx, {}) or {}
                extracted_set    = mc.get("extracted", set())
                r[f"extracted_{m}"] = ",".join(sorted(extracted_set)) if extracted_set else ""
                is_correct       = mc.get("correct", False)
                r[f"correct_{m}"] = 1 if is_correct else 0

                if is_correct:
                    correct_count += 1

            r["pct_of_models_correct"] = (
                round(correct_count / len(model_names) * 100, 1)
                if model_names else 0
            )
            rows.append(r)

        result_df = pd.DataFrame(rows)

        # Column ordering
        base_cols     = [
            "question_id", "question_text", "gold_answer", "valid_labels",
            "category", "city", "source_url", "page_title", "supporting_quotes",
        ]
        response_cols   = [f"response_{m}"       for m in model_names]
        searched_cols   = [f"searched_{m}"       for m in model_names]
        retrieved_cols  = [f"retrieved_urls_{m}" for m in model_names]
        cited_cols      = [f"cited_urls_{m}"     for m in model_names]
        extracted_cols  = [f"extracted_{m}"      for m in model_names]
        correct_cols    = [f"correct_{m}"        for m in model_names]
        col_order = (
            base_cols
            + response_cols + searched_cols + retrieved_cols + cited_cols
            + extracted_cols + correct_cols
            + ["pct_of_models_correct"]
        )
        result_df = result_df[[c for c in col_order if c in result_df.columns]]

        # ── Summary sheet ─────────────────────────────────────────────────────
        n_rows = len(result_df)
        summary_rows: list[dict] = []
        for m in model_names:
            col = f"correct_{m}"
            if n_rows and col in result_df.columns:
                accuracy = round(result_df[col].mean() * 100, 1)
            else:
                accuracy = None
            summary_rows.append({
                "model":       m,
                "total_count": n_rows,
                "accuracy":    accuracy,
            })
        summary_df = pd.DataFrame(summary_rows)

        # ── Write workbook (Summary + Results only; no Error_Analysis) ────────
        output = self.config.output_path
        output.parent.mkdir(parents=True, exist_ok=True)

        with pd.ExcelWriter(output, engine="openpyxl") as writer:
            summary_df.to_excel(writer, sheet_name="Summary", index=False)
            result_df.to_excel(writer,  sheet_name="Results", index=False)

            for sheet_name in ["Summary", "Results"]:
                ws = writer.sheets[sheet_name]
                for col_cells in ws.columns:
                    max_len = max(
                        len(str(cell.value or "")) for cell in col_cells
                    )
                    header_len = len(str(col_cells[0].value or ""))
                    ws.column_dimensions[col_cells[0].column_letter].width = (
                        min(max(max_len, header_len) + 2, 60)
                    )
                    for cell in col_cells:
                        cell.alignment = Alignment(wrap_text=True, vertical="top")
                for cell in ws[1]:
                    cell.font = Font(bold=True)

        logger.info("Results saved to %s", output)
        return output

    # ── Main orchestrator ─────────────────────────────────────────────────────

    def run(self) -> Path:
        """Execute the full MC benchmark pipeline and return the output path."""
        logger.info("Loading QA pairs from %s", self.config.input_path)
        df = pd.read_excel(self.config.input_path)

        # Rename source columns for clarity throughout the pipeline.
        if "answer" in df.columns and "gold_answer" not in df.columns:
            df = df.rename(columns={"answer": "gold_answer"})
        if "question" in df.columns and "question_text" not in df.columns:
            df = df.rename(columns={"question": "question_text"})

        if self.config.limit_rows:
            df = df.head(self.config.limit_rows)
            logger.info("Limited to first %d rows", self.config.limit_rows)

        logger.info(
            "Evaluating %d MC questions across %d models",
            len(df), len(self.config.eval_models),
        )

        # 1 ── Cold evaluation
        logger.info("=== Stage 1: Cold evaluation ===")
        (responses, timestamps, searched, cited_urls,
         retrieved_urls) = self.run_cold_eval(df)

        # 2 ── MC scoring (deterministic)
        logger.info("=== Stage 2: MC scoring ===")
        mc_scores = self.score_mc(df, responses)
        for m, scores in mc_scores.items():
            if scores:
                correct = sum(1 for s in scores.values() if s["correct"])
                total   = len(scores)
                logger.info(
                    "  %s: %d / %d correct (%.1f%%)",
                    m, correct, total, correct / total * 100 if total else 0,
                )

        # 3 ── Export
        logger.info("=== Stage 3: Export ===")
        output = self.export_results(
            df, responses,
            mc_scores,
            timestamps=timestamps,
            searched=searched,
            cited_urls=cited_urls,
            retrieved_urls=retrieved_urls,
        )

        # Print summary (MC accuracy only)
        logger.info("=== Done ===")
        for m in self.config.eval_models:
            mc_data = mc_scores.get(m, {})
            if mc_data:
                mc_corr = sum(1 for s in mc_data.values() if s["correct"])
                logger.info(
                    "  %s MC: %d/%d (%.1f%%)",
                    m, mc_corr, len(mc_data),
                    mc_corr / len(mc_data) * 100 if len(mc_data) else 0,
                )

        return output

